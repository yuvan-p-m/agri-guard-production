base_dir = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
locales_dir = os.path.join(base_dir, "src", "i18n", "locales")

canonical_keys = set(TRANSLATIONS["en"].keys())
print(f"Total SMS translation keys: {len(canonical_keys)}")

for lang, sms_obj in TRANSLATIONS.items():
    file_path = os.path.join(locales_dir, f"{lang}.json")
    if not os.path.exists(file_path):
        print(f"Error: missing file {file_path}")
        continue
    
    with open(file_path, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    # Check key completeness
    missing = canonical_keys - set(sms_obj.keys())
    if missing:
        print(f"Warning: {lang} missing keys: {missing}")
    
    data["smsDemo"] = sms_obj
    
    with open(file_path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(f"Updated {lang}.json successfully.")
