export function getLocalizedSensorExplanation(
  sensorKey: string,
  status: SensorStatus,
  lang: string
): string {
  const normLang = (lang || 'en').toLowerCase().split('-')[0];
  const sensorObj = SENSOR_EXPLANATIONS[sensorKey];
  if (!sensorObj) return '';
  const statusObj = sensorObj[status];
  if (!statusObj) return '';
  return statusObj[normLang] || statusObj['en'] || '';
}

export function getLocalizedUIText(key: string, lang: string): string {
  const normLang = (lang || 'en').toLowerCase().split('-')[0];
  const textObj = UI_TRANSLATIONS[key];
  if (!textObj) return '';
  return textObj[normLang] || textObj['en'] || '';
}

export function getLocalizedRainDisplay(isRaining: boolean, lang: string): string {
  return isRaining ? getLocalizedUIText('rainDetected', lang) : getLocalizedUIText('noRain', lang);
}

export function getLocalizedPumpState(isRunning: boolean, lang: string): string {
  return isRunning ? getLocalizedUIText('pumpActive', lang) : getLocalizedUIText('pumpStandby', lang);
}
